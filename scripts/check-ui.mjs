import { chromium } from 'playwright-core';
import assert from 'node:assert/strict';
import {mkdir,writeFile} from 'node:fs/promises';

const base=process.env.APP_URL || 'http://localhost:4317';
const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/usr/bin/google-chrome',headless:true,args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];
page.on('pageerror',e=>errors.push(e.message));
page.on('console',msg=>{if(msg.type()==='error')errors.push(msg.text());});
let watchId;
try{
  await page.goto(base);
  await page.getByRole('heading',{name:'Seu conteúdo, no ritmo certo.'}).waitFor();
  await mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Adicionar pasta',exact:true}).click();
  assert(await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).isChecked());
  await page.getByLabel('Nome da rotina').fill('QA · pasta temporária');
  await page.getByLabel('Link da pasta no Google Drive').fill('https://drive.google.com/drive/folders/qa-ui-drive-folder-001');
  await page.getByLabel('Quando enviar o próximo vídeo?').selectOption('daily');
  await page.getByLabel('Horários de envio').fill('08:00, 20:00');
  await page.getByRole('button',{name:'Criar rotina',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  await page.getByRole('heading',{name:'QA · pasta temporária Ativa'}).waitFor();
  const state=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  watchId=state.watches.find(w=>w.folder_id==='qa-ui-drive-folder-001').id;
  assert.equal(state.watches.find(w=>w.id===watchId).cadence,'daily');
  assert.equal(state.watches.find(w=>w.id===watchId).strip_metadata,true);
  await page.getByRole('button',{name:'Editar QA · pasta temporária'}).click();
  await page.locator('#watch-dialog').waitFor({state:'visible'});
  await page.getByLabel('Quando enviar o próximo vídeo?').selectOption('interval');
  await page.getByLabel('Intervalo entre envios').fill('2');
  await page.getByLabel('Unidade',{exact:true}).selectOption('60');
  await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).uncheck();
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  await page.getByText('A cada 2 horas',{exact:true}).waitFor();
  await page.getByRole('button',{name:'Editar QA · pasta temporária'}).click();
  await page.locator('#watch-dialog').waitFor({state:'visible'});
  assert(!(await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).isChecked()));
  await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).check();
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  await page.getByRole('button',{name:'Pausar QA · pasta temporária'}).click();
  await page.getByRole('heading',{name:'QA · pasta temporária Pausada'}).waitFor();
  await page.getByRole('button',{name:'Adicionar pasta',exact:true}).click();
  await page.getByLabel('Origem dos vídeos').selectOption('local');
  assert(!(await page.getByLabel('Link da pasta no Google Drive').isVisible()));
  assert(await page.getByLabel('Caminho da pasta local').isVisible());
  const rootPath=state.connections.local.rootPath;
  await page.getByLabel('Nome da rotina').fill('QA · pasta local');
  await page.getByLabel('Caminho da pasta local').fill(rootPath+'/.qa-ui-local-001');
  await page.locator('#local-source').getByRole('button',{name:'Verificar acesso',exact:true}).click();
  await page.getByRole('status').filter({hasText:'Acesso confirmado'}).waitFor();
  assert(await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).isChecked());
  await page.getByRole('button',{name:'Criar rotina',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  await page.getByRole('heading',{name:'QA · pasta local Ativa'}).waitFor();
  const localState=await page.evaluate(()=>fetch('/api/state').then(r=>r.json()));
  const localWatch=localState.watches.find(w=>w.name==='QA · pasta local');
  assert.equal(localWatch.source_type,'local');
  assert.equal(localWatch.folder_url,rootPath+'/.qa-ui-local-001');
  assert.equal(localWatch.strip_metadata,true);
  await page.getByRole('button',{name:'Editar QA · pasta local',exact:true}).click();
  await page.locator('#watch-dialog').waitFor({state:'visible'});
  assert.equal(await page.getByLabel('Origem dos vídeos').inputValue(),'local');
  assert(await page.getByLabel('Origem dos vídeos').isDisabled());
  assert(await page.getByLabel('Caminho da pasta local').getAttribute('readonly')!==null);
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  // Folder checks reject paths outside the mount, without requiring Google credentials.
  const invalid=await page.request.post(base+'/api/folders/check',{headers:{'X-Watcher-Request':'1'},data:{sourceType:'local',localPath:'../outside'}});
  assert.equal(invalid.status(),400);
  assert.match((await invalid.json()).error,/dentro/);
  await page.getByRole('button',{name:'Editar QA · pasta temporária'}).click();
  await page.locator('#watch-dialog').waitFor({state:'visible'});
  await page.getByRole('checkbox',{name:/Remover metadados do vídeo/}).uncheck();
  await page.getByRole('button',{name:'Salvar alterações',exact:true}).click();
  await page.waitForFunction(()=>!document.querySelector('#watch-dialog').open);
  await page.getByRole('heading',{name:'QA · pasta temporária Pausada'}).waitFor();
  await page.getByRole('link',{name:'Conexões',exact:true}).click();
  await page.getByText('Configurações avançadas',{exact:true}).click();
  await page.getByRole('heading',{name:'Motor de publicação',exact:true}).waitFor();
  assert.equal(await page.getByLabel('Quem gerencia as publicações?').inputValue(),'local');
  await page.getByText('Configurações avançadas',{exact:true}).click();
  await page.getByRole('heading',{name:'YouTube',exact:true}).waitFor();
  await page.getByRole('link',{name:'Abrir TikTok navegador',exact:true}).waitFor();
  await page.getByText('Credenciais do Google Drive',{exact:true}).click();
  await page.getByLabel('Client ID',{exact:true}).waitFor();
  await page.getByText('Credenciais do Google Drive',{exact:true}).click();
  await page.screenshot({path:'artifacts/connections-desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('link',{name:'Visão geral',exact:true}).click();
  await page.getByRole('heading',{name:'Seu conteúdo, no ritmo certo.'}).waitFor();
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'mobile layout must not overflow');
  await page.screenshot({path:'artifacts/dashboard-mobile.png',fullPage:true});
  assert.deepEqual(errors,[],'browser console must be free of runtime and CSP errors');
  console.log('Interface validada: pastas Drive e locais, verificação de acesso, edição, pausa, conexões e viewport móvel.');
}finally{
  if(watchId)await writeFile('artifacts/ui-fixture-id',watchId);
  await browser.close();
}
